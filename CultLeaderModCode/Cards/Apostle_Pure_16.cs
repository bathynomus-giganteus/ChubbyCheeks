namespace CultLeaderMod.CultLeaderModCode.Cards;

[RegisterCard(typeof(CultLeaderModCardPool))]
public class Apostle_Pure_16 : ModCardTemplate
{
    protected override HashSet<CardTag> CanonicalTags =>
        [CultLeaderCardTags.Apostle, CultLeaderCardTags.Pure];
    protected override IEnumerable<DynamicVar> CanonicalVars => [new DynamicVar("BlockPerStack", 1m)];
    public override IEnumerable<CardKeyword> CanonicalKeywords => [];
    public override CardAssetProfile AssetProfile =>
        new(PortraitPath: "res://CultLeaderMod/images/card_portraits/pure/欧珀粉.png");

    public Apostle_Pure_16()
        : base(2, CardType.Skill, CardRarity.Uncommon, TargetType.Self) { }

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        var owner = base.Owner.Creature;
        var block = ApostleCardEffectHelpers.PureStacks(owner) * DynamicVars["BlockPerStack"].BaseValue;
        if (block > 0)
            await CreatureCmd.GainBlock(owner, block, ValueProp.Move, cardPlay, true);
    }

    protected override void OnUpgrade()
    {
        DynamicVars["BlockPerStack"].UpgradeValueBy(1m);
    }
}
